// Fake plans host for the web preview: answers the plan.* commands as the host would and advances tasks on its own,
// so the card can be tried in every state without Electron. It enters through the same port as the app (see shortcuts-preview.ts).
import { readyTasks, validatePlan, type Plan, type PlanChoice, type PlanState, type PlanTaskRun, type PlanTemplate, type TaskResult } from '@shared/plan'
import type { HostCommand, SessionSummary } from '@shared/protocol'
import { installSettingsPreview } from './settings-preview'
import { emitPreviewEvent, registerPreviewHandler } from './shortcuts-preview'
import { installCliPreview } from './origin-fixtures'
import { taskSession, planTemplatesFixture } from './plan-fixtures'

type Answer = { ok: true; data: unknown } | { ok: false; error: string }

let installed = false
const plans = new Map<string, PlanState>()
let templates: PlanTemplate[] = planTemplatesFixture()
const timers = new Map<string, number>()
let created: ((planId: string, sessionId: string) => void) | null = null
let counter = 0

/** Tells the preview when a template creates a new plan: the fake chat adds the card. */
export function onPlanCreated(listener: ((planId: string, sessionId: string) => void) | null): void {
  created = listener
}

/** Restarts from a scenario: plans and templates go back to what the fixtures say. */
export function resetPlansPreview(list: PlanState[]): void {
  for (const timer of timers.values()) window.clearTimeout(timer)
  timers.clear()
  plans.clear()
  for (const plan of list) plans.set(plan.id, plan)
  templates = planTemplatesFixture()
}

const ok = (data: unknown): Answer => ({ ok: true, data })
const fail = (error: string): Answer => ({ ok: false, error })

function publish(state: PlanState): PlanState {
  const next = { ...state, updatedAt: Date.now() }
  plans.set(next.id, next)
  emitPreviewEvent({ type: 'plan.updated', plan: next })
  return next
}

const emptyRun = (taskId: string, plan: Plan): PlanTaskRun => {
  const spec = plan.tasks.find((x) => x.id === taskId)!
  return { taskId, status: 'pending', sessionId: null, agent: spec.agent, model: spec.model, effort: spec.effort, iteration: 1, attempt: 1, cwd: null, worktree: null, startedAt: null, endedAt: null, result: null, error: null, queuedBehind: null, waiting: false, files: null }
}

const sessionEvent = (session: SessionSummary) => emitPreviewEvent({ type: 'session.upsert', session })

/** Made-up result for a task that finishes on its own. */
function fakeResult(title: string): TaskResult {
  return {
    status: 'done',
    summary: `Done: **${title}**. Sample result generated by the preview.`,
    decisions: [],
    deviations: [],
    checks: [{ cmd: 'pnpm vitest run', exit: 0, summary: 'All tests pass' }],
    issues: [],
    questions: [],
    sideEffects: [],
    verdict: null
  }
}

/** One simulation step: running tasks finish, then ready tasks start, and it stops at stop points. */
function advance(id: string): void {
  const state = plans.get(id)
  if (!state || state.status !== 'running') return
  const now = Date.now()
  let runs = state.runs.map((r) => (r.status === 'running' && !r.waiting ? { ...r, status: 'completed' as const, endedAt: now, result: fakeResult(state.plan.tasks.find((x) => x.id === r.taskId)?.title ?? r.taskId), files: r.files ?? { count: 1, added: 12, removed: 3 } } : r))
  const finished = runs.filter((r, i) => r.status === 'completed' && state.runs[i].status === 'running').map((r) => r.taskId)
  const stop = finished.find((taskId) => state.plan.stopAfter.includes(taskId))
  let next: PlanState = { ...state, runs }
  const pending = runs.some((r) => r.status === 'pending')
  if (stop && pending) {
    publish({ ...next, status: 'paused', pause: { reason: 'stop-point', taskId: stop, message: 'Stop point: review the result before going on.', choices: ['continue', 'stop'], at: now } })
    return
  }
  const ready = readyTasks(next)
  runs = runs.map((r) => {
    if (!ready.some((x) => x.id === r.taskId)) return r
    const sessionId = `task-${id}-${r.taskId}`
    const spec = state.plan.tasks.find((x) => x.id === r.taskId)!
    sessionEvent(taskSession(id, spec, { run: 'running', agent: r.agent, model: r.model }))
    return { ...r, status: 'running' as const, sessionId, startedAt: now, endedAt: null }
  })
  next = { ...next, runs }
  if (runs.every((r) => r.status === 'completed' || r.status === 'skipped')) next = { ...next, status: 'completed', endedAt: now }
  publish(next)
  if (next.status === 'running') schedule(id)
}

function schedule(id: string): void {
  window.clearTimeout(timers.get(id))
  timers.set(id, window.setTimeout(() => advance(id), 4_000))
}

function approve(state: PlanState, workspace: 'main' | 'worktree'): PlanState {
  const now = Date.now()
  const base: PlanState = {
    ...state,
    status: 'running',
    approvedAt: now,
    pause: null,
    workspace: { kind: workspace, path: workspace === 'main' ? '/tmp/acme-app' : '/tmp/acme-app-wt', branch: workspace === 'main' ? null : 'ladder/preview', base: 'a1c9e2f' },
    runs: state.plan.tasks.map((x) => state.runs.find((r) => r.taskId === x.id) ?? emptyRun(x.id, state.plan))
  }
  const ready = readyTasks(base)
  const runs = base.runs.map((r) => {
    if (!ready.some((x) => x.id === r.taskId)) return r
    const spec = state.plan.tasks.find((x) => x.id === r.taskId)!
    sessionEvent(taskSession(state.id, spec, { run: 'running', agent: r.agent, model: r.model }))
    return { ...r, status: 'running' as const, sessionId: `task-${state.id}-${r.taskId}`, startedAt: now }
  })
  return { ...base, runs }
}

function choose(state: PlanState, choice: PlanChoice, taskId: string | undefined, reassign: Extract<HostCommand, { type: 'plan.choose' }>['reassign']): Answer {
  const target = taskId ?? state.pause?.taskId ?? null
  const now = Date.now()
  const patchRun = (patch: Partial<PlanTaskRun>) => state.runs.map((r) => (r.taskId === target ? { ...r, ...patch } : r))
  if (choice === 'stop') return ok(stop(state))
  if (choice === 'continue') return ok(resume({ ...state, pause: null }))
  if (choice === 'skip') return ok(resume({ ...state, pause: null, runs: patchRun({ status: 'skipped', endedAt: now }) }))
  const current = state.runs.find((r) => r.taskId === target)
  if (!current) return fail('That task is not part of the plan.')
  const patch: Partial<PlanTaskRun> = { status: 'running', attempt: current.attempt + 1, error: null, startedAt: now, endedAt: null, waiting: false }
  if (choice === 'reassign' && reassign) Object.assign(patch, { agent: reassign.agent, model: reassign.model, effort: reassign.effort })
  return ok(resume({ ...state, pause: null, runs: patchRun(patch) }))
}

function resume(state: PlanState): PlanState {
  const next = publish({ ...state, status: 'running' })
  schedule(next.id)
  return next
}

function stop(state: PlanState): PlanState {
  window.clearTimeout(timers.get(state.id))
  const now = Date.now()
  return publish({ ...state, status: 'stopped', pause: null, pendingUpdate: null, endedAt: now, runs: state.runs.map((r) => (r.status === 'running' || r.status === 'queued' ? { ...r, status: r.status === 'running' ? ('interrupted' as const) : ('pending' as const), waiting: false, endedAt: now } : r)) })
}

function handle(command: HostCommand): Answer | undefined {
  if (!command.type.startsWith('plan.')) return undefined
  if (command.type === 'plan.templates') return ok(templates)
  if (command.type === 'plan.deleteTemplate') {
    templates = templates.filter((x) => x.id !== command.templateId)
    return ok(null)
  }
  if (command.type === 'plan.useTemplate') {
    const template = templates.find((x) => x.id === command.templateId)
    if (!template) return fail('That template no longer exists.')
    const id = `plan-tpl-${++counter}`
    const plan: Plan = { ...template.plan, goal: command.goal }
    const now = Date.now()
    const state: PlanState = { id, sessionId: command.sessionId, projectId: 'preview', status: 'review', revision: 1, plan, author: 'claude-code', updateReason: null, pendingUpdate: null, runs: plan.tasks.map((x) => emptyRun(x.id, plan)), pause: null, workspace: null, createdAt: now, updatedAt: now, approvedAt: null, endedAt: null }
    publish(state)
    created?.(id, command.sessionId)
    return ok(state)
  }
  if (!('planId' in command)) return fail('Unknown plan command.')
  const state = plans.get(command.planId)
  if (!state) return fail('This plan no longer exists.')
  switch (command.type) {
    case 'plan.get':
      return ok(state)
    case 'plan.edit': {
      if (state.status !== 'review') return fail('The plan is no longer in review.')
      if (command.revision !== state.revision) return fail('The plan changed while you were editing: reload it and try again.')
      const check = validatePlan(command.plan)
      if (!check.ok) return fail(check.errors.join('\n'))
      const keep = new Map(state.runs.map((r) => [r.taskId, r]))
      return ok(publish({ ...state, revision: state.revision + 1, plan: check.plan, runs: check.plan.tasks.map((x) => keep.get(x.id) ?? emptyRun(x.id, check.plan)) }))
    }
    case 'plan.approve': {
      if (state.status !== 'review') return fail('The plan is no longer in review.')
      if (command.revision !== state.revision) return fail('The plan changed while you were editing: reload it and try again.')
      const next = publish(approve(state, command.workspace))
      schedule(next.id)
      return ok(next)
    }
    case 'plan.reject':
      return ok(stop(state))
    case 'plan.choose':
      return choose(state, command.choice, command.taskId, command.reassign)
    case 'plan.confirmUpdate': {
      if (!state.pendingUpdate) return fail('There is nothing to confirm.')
      const plan = command.accept ? state.pendingUpdate : state.plan
      const runs = plan.tasks.map((x) => state.runs.find((r) => r.taskId === x.id) ?? emptyRun(x.id, plan))
      return ok(resume({ ...state, plan, runs, pendingUpdate: null, updateReason: null, pause: null, revision: command.accept ? state.revision + 1 : state.revision }))
    }
    case 'plan.stop':
      return ok(stop(state))
    case 'plan.saveTemplate': {
      const template: PlanTemplate = { id: `tpl-${++counter}`, name: command.name, plan: { ...state.plan, goal: '' }, createdAt: Date.now() }
      templates = [...templates, template]
      return ok(template)
    }
    default:
      return fail('Unknown plan command.')
  }
}

/** Installs the fake host (once). It also needs `project.settings`, which the fake settings host answers. */
export function installPlansPreview(): void {
  if (installed) return
  installed = true
  installSettingsPreview()
  registerPreviewHandler(handle)
  installCliPreview()
}

